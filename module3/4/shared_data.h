#ifndef SHARED_DATA_H
#define SHARED_DATA_H

#include <stddef.h>

/* Общий размер разделяемой памяти — 4 Кбайт. */
#define SHARED_MEMORY_SIZE (4UL * 1024UL)

/* Ключ, по которому процессы находят общий сегмент памяти. */
#define SHARED_MEMORY_KEY 0x4D340001

/* Отдельный ключ для семафора System V. */
#define SEMAPHORE_KEY 0x4D340002

/*
 * Заголовок находится в начале разделяемой памяти
 * и хранит общее состояние программы.
 */
struct shared_header {
    /* Сколько байтов разделяемой памяти уже занято. */
    size_t used_size;

    /* Смещение первого блока с числами от начала памяти. */
    size_t first_block_offset;

    /* 0 — производитель ещё работает, 1 — данные закончились. */
    int producer_finished;
};

/*
 * Заголовок одного блока с массивом чисел.
 * Сами числа располагаются сразу после этой структуры.
 */
struct data_block {
    /*
     * Количество чисел в блоке.
     * Значение 0 означает, что потребитель уже обработал блок.
     */
    size_t element_count;

    /*
     * Смещение следующего блока от начала разделяемой памяти.
     * Значение 0 означает, что этот блок последний.
     */
    size_t next_block_offset;

    /* Массив переменного размера. */
    int numbers[];
};

#endif